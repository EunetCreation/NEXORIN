    public static function has(string $code): bool
    {
        return array_key_exists(strtoupper($code), self::classes());
    }

    public static function for(string $code): ?array
    {
        return self::classes()[strtoupper($code)] ?? null;
    }

    public static function rootCodeFor(string $code): ?string
    {
        return self::for($code)['root_code'] ?? null;
    }

    /** @return array<string, string> */
    public static function subcategoriesForRoot(string $rootCode): array
    {
        $rootCode = strtoupper($rootCode);
        $items = [];
        foreach (self::classes() as $code => $definition) {
            if (($definition['root_code'] ?? null) === $rootCode) {
                $items[$code] = $definition['title'];
            }
        }

        return $items;
    }

    /** @return array<int, string> */
    public static function codes(): array
    {
        return array_keys(self::classes());
    }

    public static function count(): int
    {
        return count(self::classes());
    }
